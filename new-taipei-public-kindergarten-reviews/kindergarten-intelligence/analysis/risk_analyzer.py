RULES = {
    '疑似體罰': (25, ['打小孩', '打學生', '體罰', '巴掌', '打人', '拉扯', '推倒']),
    '疑似不當管教': (20, ['辱罵', '吼小孩', '恐嚇', '罰站', '關廁所', '不當管教']),
    '疑似兒少傷害': (25, ['虐童', '受傷', '瘀青', '傷口']),
    '食安問題': (20, ['食物中毒', '過期', '發霉', '吃壞肚子']),
    '衛生問題': (10, ['蟑螂', '很髒', '環境髒亂']),
    '收退費爭議': (10, ['亂收費', '退費', '學費爭議']),
    '人力問題': (10, ['人力不足', '師生比', '無照教保', '缺老師']),
    '超收': (15, ['超收']),
    '公安問題': (20, ['消防不合格', '公安', '逃生出口', '違建']),
    '行政裁罰': (20, ['裁罰', '罰鍰', '勒令停辦', '停招', '違反幼兒教育及照顧法']),
    '家長投訴': (10, ['投訴', '申訴', '家長抗議']),
}

def analyze(item):
    text = item.get('title', '') + ' ' + item.get('content', '')
    tags = [tag for tag, (_, words) in RULES.items() if any(w in text for w in words)]
    item['risk_tags'] = tags
    item['risk_score'] = min(100, sum(RULES[t][0] for t in tags))
    return item
